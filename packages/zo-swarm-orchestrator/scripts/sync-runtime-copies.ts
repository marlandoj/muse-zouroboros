#!/usr/bin/env bun
/**
 * sync-runtime-copies.ts — keeps generated runtime copies in sync with the
 * canonical sources in THIS distribution (marlandoj/muse-zouroboros).
 *
 * Public-package layout (contrast the monorepo, where the swarm package lives
 * at packages/swarm):
 *   canonical orchestrator scripts  → packages/zo-swarm-orchestrator/scripts/
 *   generated standalone forwarders → packages/zo-swarm-orchestrator/src/standalone/
 *   canonical executor registry     → packages/zo-swarm-orchestrator/src/executor/registry/executor-registry.json
 *   generated registry copy         → packages/zo-swarm-executors/registry/executor-registry.json
 *                                     (this is what bootstrap.sh exports as SWARM_EXECUTOR_REGISTRY)
 *
 * `syncRuntimeCopies(root)` returns a list of drift failures (empty = in sync).
 * The runtime-authority tests assert zero drift against the repo root, so every
 * generated file below must be committed and current.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const ORCH = 'packages/zo-swarm-orchestrator';
const EXEC = 'packages/zo-swarm-executors';

export const runtimeCopies = [
  ...['orchestrate-v5.ts', 'orchestrate-v5-backup.ts'].map(target => ({
    path: `${ORCH}/src/standalone/${target}`, target,
  })),
  ...['mcp-server.ts', 'mcp-server-http.ts', 'swarm-hybrid-runner.ts'].map(target => ({
    path: `${ORCH}/src/standalone/${target}`, target,
  })),
  {
    path: `${EXEC}/scripts/doctor.ts`,
    target: `${ORCH}/src/executor/doctor.ts`,
  },
];
export const canonicalRegistry = `${ORCH}/src/executor/registry/executor-registry.json`;
export const generatedRegistry = `${EXEC}/registry/executor-registry.json`;

// Self-contained so export scripts can copy these entry points elsewhere.
// Resolve code beside this entry point first; workspace env vars can point at
// separate runtime data. An exported copy outside the repo needs the override.
export function renderRuntimeForwarder(target: string): string {
  const canonicalPath = target.startsWith('packages/') ? target : `${ORCH}/scripts/${target}`;
  return `#!/usr/bin/env bun
// Generated by ${ORCH}/scripts/sync-runtime-copies.ts; edit ${canonicalPath}.
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const roots: string[] = [];
for (let root = dirname(fileURLToPath(import.meta.url)); ; root = dirname(root)) {
  roots.push(root);
  if (dirname(root) === root) break;
}
if (process.env.ZOUROBOROS_WORKSPACE_ROOT) roots.push(process.env.ZOUROBOROS_WORKSPACE_ROOT);
const target = roots.map(root => join(root, '${canonicalPath}'))
  .find(path => existsSync(path) && pathToFileURL(path).href !== import.meta.url);
if (!target) throw new Error('Canonical swarm runtime missing: use the complete workspace or set ZOUROBOROS_WORKSPACE_ROOT');
await import(pathToFileURL(target).href);
`;
}

export function syncRuntimeCopies(root: string, write = false): string[] {
  const failures: string[] = [];
  const copies = runtimeCopies.map(copy => ({ ...copy, content: renderRuntimeForwarder(copy.target) }));
  copies.push({
    path: generatedRegistry, target: canonicalRegistry,
    content: readFileSync(join(root, canonicalRegistry), 'utf8'),
  });
  for (const copy of copies) {
    const path = join(root, copy.path);
    if (write) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, copy.content);
    }
    else if (!existsSync(path) || readFileSync(path, 'utf8') !== copy.content) {
      failures.push(`Runtime copy drift: ${copy.path}`);
    }
  }
  return failures;
}

if (import.meta.main) {
  const failures = syncRuntimeCopies(
    resolve(import.meta.dir, '../../..'), process.argv.includes('--write'));
  if (failures.length > 0) {
    for (const failure of failures) console.error(failure);
    process.exit(1);
  }
  console.log('runtime copies in sync');
}
